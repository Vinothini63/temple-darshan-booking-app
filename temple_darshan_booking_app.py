import sqlite3

# Open existing database
conn = sqlite3.connect("temple_darshan.db")
cursor = conn.cursor()

# Enable foreign key checking
cursor.execute("PRAGMA foreign_keys = ON")

def show_temples():
    cursor.execute("SELECT * FROM Temples")
    for row in cursor.fetchall():
        print(row)

def show_slots():
    cursor.execute("""
        SELECT s.slot_id, t.temple_name,
               s.darshan_date, s.darshan_time,
               s.ticket_price
        FROM Darshan_Slots s
        JOIN Temples t ON s.temple_id = t.temple_id
    """)
    for row in cursor.fetchall():
        print(row)

while True:
    print("\n===== TEMPLE DARSHAN BOOKING APP =====")
    print("1. View Temples")
    print("2. View Darshan Slots")
    print("3. Book Darshan")
    print("4. View Bookings")
    print("5. Cancel Booking")
    print("6. Exit")

    choice = input("Enter your choice: ")

    if choice == "1":
        show_temples()

    elif choice == "2":
        show_slots()

    elif choice == "3":
        confirm = input("Do you want to book darshan? (yes/no): ").lower()

        if confirm == "yes":
            try:
                devotee_id = int(input("Enter Devotee ID: "))
                slot_id = int(input("Enter Slot ID: "))
                tickets = int(input("Enter number of tickets: "))

                cursor.execute(
                    "SELECT ticket_price FROM Darshan_Slots WHERE slot_id = ?",
                    (slot_id,)
                )
                slot = cursor.fetchone()

                cursor.execute(
                    "SELECT devotee_id FROM Devotees WHERE devotee_id = ?",
                    (devotee_id,)
                )
                devotee = cursor.fetchone()

                if slot and devotee and tickets > 0:
                    amount = slot[0] * tickets

                    cursor.execute("""
                        INSERT INTO Bookings
                        (devotee_id, slot_id, tickets_count, booking_status)
                        VALUES (?, ?, ?, 'Booked')
                    """, (devotee_id, slot_id, tickets))

                    booking_id = cursor.lastrowid

                    cursor.execute("""
                        INSERT INTO Payments
                        (booking_id, amount, payment_status)
                        VALUES (?, ?, 'Pending')
                    """, (booking_id, amount))

                    conn.commit()

                    print("Booking successful!")
                    print("Booking ID:", booking_id)
                    print("Total amount: Rs.", amount)
                    print("Payment status: Pending")
                else:
                    print("Invalid devotee ID, slot ID, or ticket count.")

            except ValueError:
                print("Please enter numbers only for IDs and tickets.")

        else:
            print("Okay, booking not made.")

    elif choice == "4":
        cursor.execute("""
            SELECT b.booking_id, d.name, t.temple_name,
                   s.darshan_date, b.tickets_count,
                   b.booking_status
            FROM Bookings b
            JOIN Devotees d ON b.devotee_id = d.devotee_id
            JOIN Darshan_Slots s ON b.slot_id = s.slot_id
            JOIN Temples t ON s.temple_id = t.temple_id
        """)
        for row in cursor.fetchall():
            print(row)

    elif choice == "5":
        try:
            booking_id = int(input("Enter Booking ID to cancel: "))
            cursor.execute("""
                UPDATE Bookings
                SET booking_status = 'Cancelled'
                WHERE booking_id = ?
                  AND booking_status = 'Booked'
            """, (booking_id,))
            conn.commit()

            if cursor.rowcount > 0:
                print("Booking cancelled successfully!")
            else:
                print("Active booking not found.")
        except ValueError:
            print("Enter a valid Booking ID.")

    elif choice == "6":
        print("Thank you for using Temple Darshan Booking App!")
        break

    else:
        print("Invalid choice. Try again.")

conn.close()

